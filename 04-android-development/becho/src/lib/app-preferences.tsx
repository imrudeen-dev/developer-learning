export type TranslationKey = keyof typeof translations.en;

interface AppPreferencesValue {
  themeId: AppThemeId;
  theme: (typeof APP_THEMES)[AppThemeId];
  language: AppLanguage;
  loading: boolean;
  setThemeId: (themeId: AppThemeId) => void;
  setLanguage: (language: AppLanguage) => void;
  t: (key: TranslationKey) => string;
}

const AppPreferencesContext = createContext<AppPreferencesValue>({
  themeId: 'emerald',
  theme: APP_THEMES.emerald,
  language: 'en',
  loading: true,
  setThemeId: () => {},
  setLanguage: () => {},
  t: (key) => translations.en[key],
});

export function AppPreferencesProvider({ children }: { children: React.ReactNode }) {
  const [themeId, setThemeIdState] = useState<AppThemeId>('emerald');
  const [language, setLanguageState] = useState<AppLanguage>('en');
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let active = true;
    void Promise.all([
      AsyncStorage.getItem(THEME_STORAGE_KEY),
      AsyncStorage.getItem(LANGUAGE_STORAGE_KEY),
    ])
      .then(([storedTheme, storedLanguage]) => {
        if (!active) return;
        if (
          storedTheme === 'emerald' ||
          storedTheme === 'ocean' ||
          storedTheme === 'violet' ||
          storedTheme === 'light'
        ) {
          setThemeIdState(storedTheme);
        }
        if (storedLanguage === 'en' || storedLanguage === 'ta') {
          setLanguageState(storedLanguage);
        }
      })
      .catch((error: unknown) => {
        console.error('[Becho] Could not load appearance preferences:', error);
      })
      .finally(() => {
        if (active) setLoading(false);
      });

    return () => {
      active = false;
    };
  }, []);

  const setThemeId = useCallback((nextThemeId: AppThemeId) => {
    setThemeIdState(nextThemeId);
    void AsyncStorage.setItem(THEME_STORAGE_KEY, nextThemeId).catch((error: unknown) => {
      console.error('[Becho] Could not save theme preference:', error);
    });
  }, []);

  const setLanguage = useCallback((nextLanguage: AppLanguage) => {
    setLanguageState(nextLanguage);
    void AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage).catch((error: unknown) => {
      console.error('[Becho] Could not save language preference:', error);
    });
  }, []);
  const t = useCallback((key: TranslationKey) => translations[language][key], [language]);

  const value = useMemo(
    () => ({
      themeId,
      theme: APP_THEMES[themeId],
      language,
      loading,
      setThemeId,
      setLanguage,
      t,
    }),
    [themeId, language, loading, setThemeId, setLanguage, t]
  );

  return <AppPreferencesContext.Provider value={value}>{children}</AppPreferencesContext.Provider>;
}

export function useAppPreferences() {
  return useContext(AppPreferencesContext);
}
